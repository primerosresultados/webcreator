// Check if already installed
$lockFile = __DIR__ . '/.installed.lock';
$configFile = __DIR__ . '/../config/database.php';

if (file_exists($lockFile)) {
    die('
    <!DOCTYPE html><html><head><meta charset="UTF-8"><title>Ya instalado</title>
