    <body><div class="box"><h1>⚠️ Sistema ya instalado</h1><p>Si necesitas reinstalar, elimina el archivo <code>install/.installed.lock</code> y <code>config/database.php</code></p>
    <p><a href="../admin/">Ir al panel de administración →</a></p></div></body></html>');
}

