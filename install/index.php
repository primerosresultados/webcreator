// ============================================
// STEP 2: Process installation
// ============================================
if ($_SERVER['REQUEST_METHOD'] === 'POST' && $step === 2) {
    $dbHost = trim($_POST['db_host'] ?? '');
    $dbName = trim($_POST['db_name'] ?? '');
    $dbUser = trim($_POST['db_user'] ?? '');
    $dbPass = $_POST['db_pass'] ?? '';
    $siteName = trim($_POST['site_name'] ?? 'Mi Sitio Web');
    $siteUrl = trim($_POST['site_url'] ?? '');
    $adminUser = trim($_POST['admin_user'] ?? '');
    $adminEmail = trim($_POST['admin_email'] ?? '');
    $adminPass = $_POST['admin_pass'] ?? '';
    $adminPassConfirm = $_POST['admin_pass_confirm'] ?? '';

    // Validate inputs
    if (empty($dbHost)) $errors[] = 'El host de la base de datos es requerido.';
    if (empty($dbName)) $errors[] = 'El nombre de la base de datos es requerido.';
    if (empty($dbUser)) $errors[] = 'El usuario de la base de datos es requerido.';
    if (empty($adminUser)) $errors[] = 'El nombre de usuario admin es requerido.';
    if (empty($adminEmail) || !filter_var($adminEmail, FILTER_VALIDATE_EMAIL)) $errors[] = 'Email de administrador inválido.';
    if (strlen($adminPass) < 8) $errors[] = 'La contraseña debe tener al menos 8 caracteres.';
    if ($adminPass !== $adminPassConfirm) $errors[] = 'Las contraseñas no coinciden.';

    if (empty($errors)) {
        // Test database connection
        try {
            $pdo = new PDO(
                "mysql:host={$dbHost};charset=utf8mb4",
                $dbUser,
                $dbPass,
                [
                    PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                    PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
                    PDO::ATTR_EMULATE_PREPARES => false
                ]
            );

            // Create database if it doesn't exist
            $pdo->exec("CREATE DATABASE IF NOT EXISTS `{$dbName}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
            $pdo->exec("USE `{$dbName}`");

            // Execute schema
            $schema = file_get_contents(__DIR__ . '/schema.sql');
            $pdo->exec($schema);

            // Create admin user
            $hashedPassword = password_hash($adminPass, PASSWORD_BCRYPT, ['cost' => 12]);
            $stmt = $pdo->prepare("INSERT INTO `users` (`username`, `email`, `password`, `full_name`, `role`, `is_active`) VALUES (?, ?, ?, ?, 'superadmin', 1)");
            $stmt->execute([$adminUser, $adminEmail, $hashedPassword, $adminUser]);

            // Update site settings
            $pdo->prepare("UPDATE `settings` SET `setting_value` = ? WHERE `setting_key` = 'site_name'")->execute([$siteName]);
            $pdo->prepare("UPDATE `settings` SET `setting_value` = ? WHERE `setting_key` = 'contact_email'")->execute([$adminEmail]);

            // Generate CSRF secret
            $csrfSecret = bin2hex(random_bytes(32));

            // Write config file
            $configContent = "<?php\n";
            $configContent .= "/**\n * Auto-generated by WebCreator Installer\n * Date: " . date('Y-m-d H:i:s') . "\n */\n\n";
            $configContent .= "define('DB_HOST', " . var_export($dbHost, true) . ");\n";
            $configContent .= "define('DB_NAME', " . var_export($dbName, true) . ");\n";
            $configContent .= "define('DB_USER', " . var_export($dbUser, true) . ");\n";
            $configContent .= "define('DB_PASS', " . var_export($dbPass, true) . ");\n";
            $configContent .= "define('DB_CHARSET', 'utf8mb4');\n\n";
            $configContent .= "define('SITE_NAME', " . var_export($siteName, true) . ");\n";
            $configContent .= "define('SITE_URL', " . var_export($siteUrl, true) . ");\n";
            $configContent .= "define('ADMIN_EMAIL', " . var_export($adminEmail, true) . ");\n\n";
            $configContent .= "define('CSRF_SECRET', " . var_export($csrfSecret, true) . ");\n";
            $configContent .= "define('SESSION_LIFETIME', 3600);\n";

            // Ensure config directory exists
            if (!is_dir(dirname($configFile))) {
                mkdir(dirname($configFile), 0755, true);
            }
            file_put_contents($configFile, $configContent);

            // Create uploads directory
            $uploadsDir = __DIR__ . '/../uploads';
            if (!is_dir($uploadsDir)) {
                mkdir($uploadsDir, 0755, true);
            }
            // Create .htaccess for uploads (only allow images)
            $uploadsHtaccess = "# Only allow image files\n";
            $uploadsHtaccess .= "<FilesMatch \"(?i)\\.(php|php3|php4|php5|phtml|pl|py|cgi|sh|bash)$\">\n";
            $uploadsHtaccess .= "    Order deny,allow\n";
            $uploadsHtaccess .= "    Deny from all\n";
            $uploadsHtaccess .= "</FilesMatch>\n\n";
            $uploadsHtaccess .= "# Disable PHP execution\n";
            $uploadsHtaccess .= "php_flag engine off\n";
            file_put_contents($uploadsDir . '/.htaccess', $uploadsHtaccess);

            // Create lock file
            file_put_contents($lockFile, 'Installed on: ' . date('Y-m-d H:i:s') . "\nBy: {$adminEmail}");

            $success = true;

        } catch (PDOException $e) {
            $errors[] = 'Error de conexión a la base de datos: ' . $e->getMessage();
        } catch (Exception $e) {
            $errors[] = 'Error durante la instalación: ' . $e->getMessage();
        }
    }

    if (!empty($errors)) {
        $step = 2; // Stay on form with errors
    }
}
